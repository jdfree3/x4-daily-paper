#!/usr/bin/env python3
"""Build index.lua and lockscreen.lua from src/: the device has no require for package files, so
src/common.lua goes in front of each as `local C = (function() ... end)()`."""
import os
here = os.path.dirname(os.path.abspath(__file__))
common = open(os.path.join(here, 'src', 'common.lua')).read()
head = '-- GENERATED by bundle.py from src/common.lua and src/%s -- edit those, not this file.\n'
for out, src in (('index.lua', 'main.lua'), ('lockscreen.lua', 'lock.lua')):
    body = open(os.path.join(here, 'src', src)).read()
    open(os.path.join(here, out), 'w').write((head % src) + 'local C = (function()\n' + common + 'end)()\n\n' + body)
    print(out, 'written')
